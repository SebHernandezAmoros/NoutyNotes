import { expect, test } from '@playwright/test';
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { serializeWorkspace } from '../../packages/storage/src/workspace-codec';
import { readWorkspaceArchive, writeWorkspaceArchive } from '../../packages/storage/src/workspace-archive';
import { auxiliaryRef, detachmentPdf, detachmentPdfRef, detachmentPng, detachmentRef, detachmentWorkspace } from '../fixtures/asset-detachment';
import { isCompactWidth } from './support';

function value<T>(result: { readonly ok: true; readonly value: T } | { readonly ok: false; readonly issues: readonly unknown[] }): T {
  if (!result.ok) throw new Error(JSON.stringify(result.issues));
  return result.value;
}

test('U2-C: vista previa, políticas y excepciones no cambian documentos ni bytes', async ({ page }, info) => {
  const source = detachmentWorkspace();
  const binary = new Uint8Array(Buffer.from(detachmentPng, 'base64'));
  const assets = { [detachmentRef]: binary, [auxiliaryRef]: binary, [detachmentPdfRef]: new Uint8Array(Buffer.from(detachmentPdf)) };
  const bytes = value(writeWorkspaceArchive(value(serializeWorkspace(source)), assets));
  writeFileSync('artifacts/u2-c-fixture.zip', bytes);
  await page.emulateMedia({ colorScheme: info.project.name === 'mobile' ? 'light' : 'dark' });
  await page.addInitScript(() => Object.defineProperty(window, 'showDirectoryPicker', { value: undefined, configurable: true }));
  await page.goto('./');
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Importar un ZIP', exact: true }).click();
  await (await chooser).setFiles({ name: 'u2-c.zip', mimeType: 'application/zip', buffer: Buffer.from(bytes) });
  await expect(page.getByRole('heading', { name: 'Laboratorio U2-C', exact: true })).toBeVisible();
  if (isCompactWidth(page)) await page.getByRole('button', { name: 'Más secciones', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir los assets', exact: true }).click();
  const detail = page.getByTestId('asset-detail');
  await page.getByRole('button', { name: 'Ver planificador.png', exact: true }).click();
  await detail.getByRole('button', { name: 'Consultar uso', exact: true }).click();
  const open = detail.getByRole('button', { name: 'Previsualizar plan', exact: true });
  await open.focus();
  await page.keyboard.press('Enter');
  const preview = page.getByTestId('asset-detachment-preview');
  await expect(preview).toContainText('Vista previa. No se realizarán cambios ni se eliminarán archivos');
  await expect(preview.getByTestId('asset-plan-status')).toHaveText('Plan revisable con cobertura parcial');
  await expect(preview.getByTestId('asset-plan-occurrence')).toHaveCount(5);
  await expect(preview).toContainText('Marcadores: 4');
  await expect(preview).toContainText('Tarjetas conservadas: 1');
  await expect(preview).toContainText('Nota en Archivo');
  await expect(preview).toContainText('Nota en Papelera');
  await expect(preview.getByRole('button', { name: /Ejecutar|Aplicar|Eliminar|Purgar|Confirmar/ })).toHaveCount(0);
  const general = preview.getByRole('button', { name: 'Política general: proponer quitar bloque', exact: true });
  await general.focus();
  await page.keyboard.press('Enter');
  await expect(preview).toContainText('Bloques que se quitarían: 4');
  const first = preview.getByTestId('asset-plan-occurrence').first();
  await expect(first).toContainText('Bloque 1');
  await first.getByRole('button', { name: 'Proponer marcador', exact: true }).click();
  await expect(first.getByTestId('asset-plan-proposal')).toContainText('Se conservaría un marcador');
  await expect(preview).toContainText('Bloques que se quitarían: 3');
  await expect(preview).toContainText('Marcadores: 1');
  expect(await preview.evaluate((element) => element.scrollWidth > element.clientWidth + 1)).toBe(false);
  await preview.getByText('Vista previa. No se realizarán cambios ni se eliminarán archivos', { exact: true }).evaluate((element) => element.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: `artifacts/u2-c-preview-${info.project.name}.png` });
  const lastControl = preview.getByTestId('asset-plan-occurrence').last().getByRole('button', { name: 'Usar política general', exact: true });
  await lastControl.scrollIntoViewIfNeeded();
  await expect(lastControl).toBeVisible();
  const lastBox = await lastControl.boundingBox();
  expect(lastBox).not.toBeNull();
  if (lastBox) {
    expect(lastBox.y).toBeGreaterThanOrEqual(0);
    expect(lastBox.y + lastBox.height).toBeLessThanOrEqual(page.viewportSize()!.height + 1);
  }
  await page.screenshot({ path: `artifacts/u2-c-last-owner-${info.project.name}.png` });
  await preview.getByRole('button', { name: 'Recalcular vista previa', exact: true }).click();
  await expect(preview).toContainText('Marcadores: 4');
  await expect(preview).toContainText('Bloques que se quitarían: 0');
  await preview.getByRole('button', { name: 'Cerrar vista previa', exact: true }).click();
  await page.getByRole('button', { name: 'Ver auxiliar.png', exact: true }).click();
  await detail.getByRole('button', { name: 'Consultar uso', exact: true }).click();
  await detail.getByRole('button', { name: 'Previsualizar plan', exact: true }).click();
  await expect(preview.getByTestId('asset-plan-status')).toHaveText('Plan con referencias o decisiones sin resolver');
  await expect(preview).toContainText('no tiene transformación');
  await preview.getByTestId('asset-plan-status').evaluate((element) => element.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: `artifacts/u2-c-blocked-${info.project.name}.png` });
  await preview.getByRole('button', { name: 'Cerrar vista previa', exact: true }).click();
  await page.getByRole('button', { name: 'Ver planificador.pdf', exact: true }).click();
  await detail.getByRole('button', { name: 'Consultar uso', exact: true }).click();
  await detail.getByRole('button', { name: 'Previsualizar plan', exact: true }).click();
  await expect(preview).toContainText('Tarjeta PDF conservada');
  await expect(preview).toContainText('Se conservaría la tarjeta');
  await expect(preview).toContainText('Tarjetas conservadas: 1');
  await page.getByRole('button', { name: 'Volver al tablero', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar este espacio como ZIP', exact: true }).click();
  const file = await (await download).path();
  if (!file) throw new Error('No se obtuvo ZIP.');
  const after = value(readWorkspaceArchive(new Uint8Array(readFileSync(file))));
  expect(after.workspace).toEqual(source);
  expect(after.assets).toEqual(assets);
});
