export type TranslationKey = keyof typeof TRANSLATIONS;

/**
 * Texto en el idioma indicado. Una clave desconocida no rompe: devuelve la propia clave. `params`
 * sustituye marcadores `{nombre}` por su valor (interpolación simple, sin plurales ni formatos).
 */
export function t(key: TranslationKey, locale: Locale, params?: Readonly<Record<string, string>>): string {
  const entry = TRANSLATIONS[key] as { readonly es: string; readonly en: string } | undefined;
  const text = entry ? entry[locale] : key;
  if (!params) return text;
  return Object.entries(params).reduce((acc, [name, value]) => acc.split(`{${name}}`).join(value), text);
}
